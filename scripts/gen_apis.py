#!/usr/bin/env python3
"""Emit ups/apis.gen.go client accessors from scripts/manifest.yaml."""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

# Hand-written *Client() helpers already exist for these packages.
SKIP = {
    "oauthclientcredentials",
    "rating",
    "shipping",
    "tracking",
    "addressvalidation",
}

NICER = {
    "commerceguard": "CommerceGuard",
    "customsdetail": "CustomsDetail",
    "dangerousgoods": "DangerousGoods",
    "deliverydefense": "DeliveryDefense",
    "deliveryintercept": "DeliveryIntercept",
    "forwarding": "Forwarding",
    "globalcheckout": "GlobalCheckout",
    "interactiveguidance": "InteractiveGuidance",
    "landedcost": "LandedCost",
    "locator": "Locator",
    "oauthauthcode": "OAuthAuthCode",
    "paperless": "Paperless",
    "pickup": "Pickup",
    "pickupnotification": "PickupNotification",
    "prenotification": "PreNotification",
    "protecteddeliverytoken": "ProtectedDeliveryToken",
    "quantumview": "QuantumView",
    "scsinventory": "SCSInventory",
    "scslogistics": "SCSLogistics",
    "smartpickup": "SmartPickup",
    "timeintransit": "TimeInTransit",
    "tradedirect": "TradeDirect",
    "exportassure": "ExportAssure",
    "pickuppoints": "PickupPoints",
    "scstransportation": "SCSTransportation",
    "trackalert": "TrackAlert",
    "trackalertenhanced": "TrackAlertEnhanced",
    "worldease": "WorldEase",
}


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    manifest = root / "scripts" / "manifest.yaml"
    out = root / "ups" / "apis.gen.go"
    doc = yaml.safe_load(manifest.read_text(encoding="utf-8"))

    imports: list[str] = []
    methods: list[str] = []
    for a in doc["apis"]:
        pkg = a["package"]
        if pkg in SKIP:
            continue
        imports.append(f'\t{pkg} "github.com/Bef-Ship/ups-sdk/internal/generated/{pkg}"')
        nicer = NICER.get(pkg, "".join(p[:1].upper() + p[1:] for p in pkg.split()))
        methods.append(
            f"""
// {nicer}Client returns a generated {a["id"]} API client for the configured environment.
func (c *Client) {nicer}Client() (*{pkg}.ClientWithResponses, error) {{
	return {pkg}.NewClientWithResponses(
		ServerURL(c.cfg.Environment, "{pkg}"),
		{pkg}.WithHTTPClient(c.http),
	)
}}
"""
        )

    content = (
        "// Code generated by scripts/gen_apis.py from manifest.yaml. DO NOT EDIT.\n"
        "package ups\n\n"
        "import (\n"
        + "\n".join(imports)
        + "\n)\n"
        + "".join(methods)
    )
    out.write_text(content, encoding="utf-8")
    print(f"→ wrote {out} ({len(methods)} accessors)", file=sys.stderr)


if __name__ == "__main__":
    main()
