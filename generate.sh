#!/usr/bin/env bash
# Fetch UPS official OpenAPI specs, patch them, generate Go clients into internal/generated.
# Official YAML is NEVER committed — only downloaded into .cache/specs.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

OAPI_CODEGEN_VERSION="${OAPI_CODEGEN_VERSION:-v2.5.0}"
export PATH="$(go env GOPATH)/bin:${PATH}"

if ! command -v oapi-codegen >/dev/null 2>&1; then
  echo "installing oapi-codegen@${OAPI_CODEGEN_VERSION} ..."
  go install "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@${OAPI_CODEGEN_VERSION}"
fi

if ! command -v python3 >/dev/null 2>&1; then
  echo "python3 required" >&2
  exit 1
fi
python3 -c "import yaml" 2>/dev/null || {
  echo "PyYAML required: pip3 install pyyaml" >&2
  exit 1
}

MANIFEST="${ROOT}/scripts/manifest.yaml"
PREPROCESS="${ROOT}/scripts/preprocess.py"
SPEC_CACHE="${ROOT}/.cache/specs"
OUT_ROOT="${ROOT}/internal/generated"
TMPDIR="$(mktemp -d "${TMPDIR:-/tmp}/ups-sdk-gen.XXXXXX")"
trap 'rm -rf "$TMPDIR"' EXIT

mkdir -p "$SPEC_CACHE" "$OUT_ROOT"

SPEC_REPO="$(python3 - "$MANIFEST" <<'PY'
import sys, yaml
doc = yaml.safe_load(open(sys.argv[1], encoding="utf-8"))
print(doc.get("spec_repo", "https://raw.githubusercontent.com/UPS-API/api-documentation/main").rstrip("/"))
PY
)"

# Emit ServerURL lookup into the public ups package.
python3 - "$MANIFEST" "${ROOT}/ups/servers.gen.go" <<'PY'
import sys, yaml
manifest, out_path = sys.argv[1], sys.argv[2]
doc = yaml.safe_load(open(manifest, encoding="utf-8"))
lines = [
    "// Code generated by generate.sh from scripts/manifest.yaml. DO NOT EDIT.",
    "package ups",
    "",
    "type apiServer struct{ CIE, Prod string }",
    "",
    "var apiServers = map[string]apiServer{",
]
for a in doc["apis"]:
    pkg, cie, prod = a["package"], a["server_cie"], a["server_prod"]
    lines.append(f'\t"{pkg}": {{CIE: "{cie}", Prod: "{prod}"}},')
lines += [
    "}",
    "",
    "// ServerURL returns the UPS base URL for an API package and environment.",
    '// env is "production" or anything else (sandbox/CIE).',
    "func ServerURL(env, apiPackage string) string {",
    "\ts, ok := apiServers[apiPackage]",
    "\tif !ok {",
    "\t\treturn BaseURL(env)",
    "\t}",
    '\tif env == "production" {',
    "\t\treturn s.Prod",
    "\t}",
    "\treturn s.CIE",
    "}",
    "",
]
open(out_path, "w", encoding="utf-8").write("\n".join(lines))
print(f"→ wrote {out_path}")
PY

ENTRIES_FILE="${TMPDIR}/entries.txt"
python3 - "$MANIFEST" <<'PY' >"$ENTRIES_FILE"
import sys, yaml
doc = yaml.safe_load(open(sys.argv[1], encoding="utf-8"))
for a in doc["apis"]:
    print("|".join([a["package"], a["file"], a["server_cie"], a["server_prod"], a["id"]]))
PY

fail=0
count=0
while IFS='|' read -r pkg file server_cie server_prod id; do
  count=$((count + 1))
  cached="${SPEC_CACHE}/${file}"
  # Optional: seed from a local mirror (never committed). Example:
  #   SPEC_LOCAL_DIR=/path/to/UPS-API/api-documentation make generate
  if [[ -n "${SPEC_LOCAL_DIR:-}" && -f "${SPEC_LOCAL_DIR}/${file}" ]]; then
    echo "· local ${file}"
    cp "${SPEC_LOCAL_DIR}/${file}" "$cached"
  elif [[ ! -f "$cached" ]] || [[ "${FORCE_FETCH:-}" == "1" ]]; then
    url="${SPEC_REPO}/${file}"
    echo "↓ fetch ${file}"
    if ! curl -fsSL --connect-timeout 30 --max-time 180 --retry 5 --retry-delay 2 \
        -o "${cached}.tmp" "$url"; then
      echo "fetch failed: ${url}" >&2
      fail=1
      rm -f "${cached}.tmp"
      continue
    fi
    mv "${cached}.tmp" "$cached"
  else
    echo "· cache hit ${file}"
  fi

  cleaned="${TMPDIR}/${pkg}.yaml"
  out_dir="${OUT_ROOT}/${pkg}"
  mkdir -p "$out_dir"
  echo "→ generate ${pkg} (${id})"
  if ! python3 "$PREPROCESS" \
      --in "$cached" \
      --out "$cleaned" \
      --server-cie "$server_cie" \
      --server-prod "$server_prod"; then
    echo "preprocess failed: ${id}" >&2
    fail=1
    continue
  fi

  size=$(wc -c <"$cleaned" | tr -d ' ')
  if [[ "$size" -gt 800000 ]]; then
    if ! oapi-codegen -generate types -package "$pkg" -o "${out_dir}/types.gen.go" "$cleaned"; then
      echo "codegen types failed: ${id}" >&2
      fail=1
      continue
    fi
    if ! oapi-codegen -generate client -package "$pkg" -o "${out_dir}/client.gen.go" "$cleaned"; then
      echo "codegen client failed: ${id}" >&2
      fail=1
      continue
    fi
  else
    rm -f "${out_dir}/types.gen.go"
    if ! oapi-codegen -generate types,client -package "$pkg" -o "${out_dir}/client.gen.go" "$cleaned"; then
      echo "codegen failed: ${id}" >&2
      fail=1
      continue
    fi
  fi
done <"$ENTRIES_FILE"

# Emit ups package API accessors (except hand-written core clients).
python3 "${ROOT}/scripts/gen_apis.py"

# Format generated Go
if command -v gofmt >/dev/null 2>&1; then
  while IFS= read -r -d '' f; do
    gofmt -w "$f"
  done < <(find "$OUT_ROOT" -name '*.go' -print0)
  gofmt -w "${ROOT}/ups/servers.gen.go" "${ROOT}/ups/apis.gen.go" 2>/dev/null || true
fi

if [[ "$fail" -ne 0 ]]; then
  echo "generate finished with errors (${count} packages attempted)" >&2
  exit 1
fi
echo "generate done (${count} packages)."
